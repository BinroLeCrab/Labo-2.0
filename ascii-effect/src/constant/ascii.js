export const getAscii = (
	b,
	medianBrightness = 5,
	mode = "default",
	contrast = false
) => {

	if (mode === "bichrome") {
		if (b >= medianBrightness) {
			return c_Ascii[mode][1];
		} else {
			return c_Ascii[mode][0];
		}
	}

	const row = c_Ascii[mode][b];

	if (mode === "default") {
		if (row.length === 1) return row[0];
		return row[Math.floor(Math.random() * row.length)];
	} else if (contrast) {
		return row[1];
	} else {
		return row[0];
	}
};
